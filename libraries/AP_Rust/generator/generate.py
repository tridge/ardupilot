"""Generate the C and Rust sides of the experimental host-call ABI."""

import argparse
import hashlib
import json
import re
from pathlib import Path

import bindings
import contracts

ROOT = Path(__file__).resolve().parents[1]
TYPES = {
    'void': ('void', '()'), 'u8': ('uint8_t', 'u8'), 'u32': ('uint32_t', 'u32'),
    'i32': ('int32_t', 'i32'), 'u64': ('uint64_t', 'u64'),
    'pointer': ('void *', '*mut core::ffi::c_void'),
    'const_bytes': ('const uint8_t *', '*const u8'), 'mut_bytes': ('uint8_t *', '*mut u8'),
}
# Changing the generated header prefix/layout must change this salt.
LAYOUT = 'AP_Rust.HostApi.v1:u32_version,u32_size,u8_fingerprint[16],ordered_function_pointers'


def identifier(name):
    if not isinstance(name, str) or not re.fullmatch('[A-Za-z_][A-Za-z0-9_]*', name):
        raise ValueError('invalid identifier')
    return name


def generate(spec, binding_spec=None):
    if binding_spec is None:
        binding_spec = bindings.specification()
    if type(spec['version']) is not int or not 0 < spec['version'] <= 0xFFFFFFFF:
        raise ValueError('invalid ABI version')
    names = set()
    for function in spec['functions']:
        name = identifier(function['name'])
        if name in names or name in ('version', 'size', 'fingerprint'):
            raise ValueError('duplicate or reserved function name')
        names.add(name)
        if function['return'] not in TYPES or function['args'][:1] != [['context', 'pointer']]:
            raise ValueError('invalid host function')
        arguments = set()
        for name, kind in function['args']:
            identifier(name)
            if name in arguments or kind not in TYPES or kind == 'void':
                raise ValueError('invalid argument')
            arguments.add(name)
    # This identity is the frozen core C ABI, never the binding catalogue.
    required = spec['required_functions']
    if type(required) is not int or not 0 < required <= len(spec['functions']):
        raise ValueError('invalid core ABI prefix')
    identity = dict(host=dict(spec, functions=spec['functions'][:required]))
    canonical = LAYOUT.encode() + b'\n' + json.dumps(identity, sort_keys=True, separators=(',', ':')).encode()
    fingerprint = hashlib.sha256(canonical).digest()[:16]
    fingerprint_values = ', '.join(f'0x{byte:02x}' for byte in fingerprint)
    notice = '// SPDX-License-Identifier: GPL-3.0-or-later\n// Generated by generator/generate.py; do not edit.\n'
    cpp = [notice, '#pragma once', '#include <stddef.h>', '#include <stdint.h>', '',
           f'#define AP_RUST_ABI_VERSION {spec["version"]}U',
           f'#define AP_RUST_API_FINGERPRINT {{{fingerprint_values}}}', '']
    rust = [notice, f'pub const ABI_VERSION: u32 = {spec["version"]};',
            f'pub const API_FINGERPRINT: [u8; 16] = [{fingerprint_values}];', '']
    for name, value in spec['status'].items():
        identifier(name)
        if type(value) is not int or not -(1 << 31) <= value < 1 << 31:
            raise ValueError('invalid status value')
        cpp.append(f'#define AP_RUST_STATUS_{name} ({value})')
        rust.append(f'pub const STATUS_{name}: i32 = {value};')
    cpp += ['', 'typedef struct AP_RustHostApi {', '    uint32_t version;', '    uint32_t size;',
            '    uint8_t fingerprint[16];']
    rust += ['', '#[repr(C)]', 'pub struct HostApi {', '    pub version: u32,', '    pub size: u32,',
             '    pub fingerprint: [u8; 16],']
    # Rust uses nullable function pointers so entry validation can reject an
    # incomplete host table without first constructing invalid Rust values.
    for function in spec['functions']:
        name, result = function['name'], function['return']
        c_args = ', '.join(f'{TYPES[kind][0]} {arg}' for arg, kind in function['args'])
        r_args = ', '.join(f'{arg}: {TYPES[kind][1]}' for arg, kind in function['args'])
        cpp.append(f'    {TYPES[result][0]} (*{name})({c_args});')
        rust.append(f'    pub {name}: Option<unsafe extern "C" fn({r_args}) -> {TYPES[result][1]}>,')
    cpp += ['} AP_RustHostApi;', '']
    cpp += ['#ifdef __cplusplus', '#define AP_RUST_LAYOUT_ASSERT static_assert', '#else',
            '#define AP_RUST_LAYOUT_ASSERT _Static_assert', '#endif']
    offsets = [('version', '0'), ('size', '4'), ('fingerprint', '8')]
    offsets += [(f['name'], f'24 + {i} * sizeof(void *)') for i, f in enumerate(spec['functions'])]
    for name, offset in offsets:
        cpp.append(f'AP_RUST_LAYOUT_ASSERT(offsetof(AP_RustHostApi, {name}) == {offset}, "HostApi.{name} layout");')
    cpp += [f'AP_RUST_LAYOUT_ASSERT(sizeof(AP_RustHostApi) == 24 + {len(names)} * sizeof(void *), "HostApi size");',
            '#undef AP_RUST_LAYOUT_ASSERT', '']
    rust += ['}', '', 'const _: () = {']
    for name, offset in offsets:
        offset = offset.replace('sizeof(void *)', 'core::mem::size_of::<*const ()>()')
        rust.append(f'    assert!(core::mem::offset_of!(HostApi, {name}) == {offset});')
    rust += [f'    assert!(core::mem::size_of::<HostApi>() == 24 + {len(names)} * core::mem::size_of::<*const ()>());',
             '};', '', 'impl HostApi {', '    pub fn is_valid(&self) -> bool {',
             '        self.version == ABI_VERSION', '            && self.size as usize >= core::mem::size_of::<Self>()',
             '            && self.fingerprint == API_FINGERPRINT']
    rust += [f'            && self.{function["name"]}.is_some()' for function in spec['functions']]
    rust += ['    }', '}', '']
    contract = dict(abi_version=spec['version'], fingerprint=fingerprint.hex())
    outputs = {'HostApi.h': '\n'.join(cpp), 'sdk/src/api.rs': '\n'.join(rust),
               'sdk/abi.json': json.dumps(contract, indent=2) + '\n'}
    outputs.update(bindings.emit(binding_spec))
    outputs.update(contracts.emit(binding_spec, notice))
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if checked-in generated files differ')
    parser.add_argument('--check-compatibility', type=Path, help='require contracts from an earlier imports.json catalogue')
    args = parser.parse_args()
    outputs = generate(json.loads((ROOT / 'generator/host_api.json').read_text()))
    if args.check_compatibility:
        contracts.check_compatibility(json.loads(args.check_compatibility.read_text()),
                                      json.loads(outputs['generator/imports.json']))
    for name, content in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'stale generated file: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == '__main__':
    main()
